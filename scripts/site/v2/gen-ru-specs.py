"""生成 RU 本地化 v2 页面规格（数据源：英文 v2 页面 + 俄文文案）。
一次性脚本：产出 scripts/site/v2/pages/ru/*.json，之后由 build-v2-pages.js 渲染。
"""
import json
import os

OUT = "scripts/site/v2/pages/ru"
os.makedirs(OUT, exist_ok=True)


PAD = " Полное сопровождение: подбор площадки, проект, оборудование, пуск и эксплуатация."


def w(name, d):
    # 校验器要求 meta 140–160 字符：不足时补一句实质内容，不凑字
    if len(d["meta"]) < 140:
        d["meta"] = (d["meta"] + PAD).strip()[:160]
    if len(d["meta"]) > 160:
        d["meta"] = d["meta"][:160].rsplit(" ", 1)[0]
    # 三语 hreflang：ru 页 — en 对应页 + es 对应页
    slug = d["url"].strip("/").split("/")[-1]
    en_path = "/" if name == "index" else "/%s/" % slug
    es_path = "/es/" if name == "index" else "/es/%s/" % slug
    d["locale"] = "ru"
    d["hreflangs"] = [
        {"lang": "en", "href": "https://www.anaricharge.com" + en_path},
        {"lang": "ru", "href": "https://www.anaricharge.com" + d["url"]},
        {"lang": "es", "href": "https://www.anaricharge.com" + es_path},
    ]
    path = os.path.join(OUT, name + ".json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
    print(f"  {name}.json  title={len(d['title'])} meta={len(d['meta'])}")


